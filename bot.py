LRM = "\u200e"
W_NUM, W_LBL, W_AMT = 4, 17, 7


def _wrap(text: str, width: int) -> list:
    return textwrap.wrap(text, width, break_long_words=True) or [""]


def _row_lines(side: str, num: str, label: str, amt: str) -> list:
    indent = 0 if side == "D" else 2
    lbl = _wrap(label, W_LBL - indent)
    am = _wrap(amt, W_AMT)
    out = []
    for i in range(max(len(lbl), len(am))):
        l = lbl[i] if i < len(lbl) else ""
        a = (am[i] if i < len(am) else "").center(W_AMT)
        blank = " " * W_AMT
        cells = (
            a if side == "C" else blank,
            a if side == "D" else blank,
            l.rjust(W_LBL - indent) + " " * indent,
            (num if i == 0 else "").center(W_NUM),
        )
        out.append(LRM + "│" + "│".join(cells) + "│")
    return out


def entry_table(item: dict) -> str:
    widths = (W_AMT, W_AMT, W_LBL, W_NUM)
    line = lambda l, m, r: LRM + l + m.join("─" * w for w in widths) + r
    head = ("دائن".center(W_AMT), "مدين".center(W_AMT), "البيان".center(W_LBL), "رقم".center(W_NUM))
    lines = [LRM + item.get("date", "N/12/31"), line("┌", "┬", "┐"), LRM + "│" + "│".join(head) + "│", line("├", "┼", "┤")]
    for r in item["rows"]:
        if r[0] == "-":
            lines.append(line("├", "┼", "┤"))
        else:
            lines += _row_lines(*r)
    lines.append(line("└", "┴", "┘"))
    return "\n".join(lines)


def entry_message(ui: int, ii: int) -> str:
    it = ENTRY_UNITS[ui]["items"][ii]
    msg = f"🧾 <b>{esc(it['title'])}</b>\n\n<pre>{esc(entry_table(it))}</pre>"
    if it.get("note"):
        msg += f"\n\n📝 {esc(it['note'])}"
    return msg + "\n\n💡 قيد ثابت في رصيدك! 🥳"


def search_entries(query: str, unit: int = None, limit: int = 3) -> list:
    ranked = sorted(
        ((score(query, it) + (0.01 if it["unit"] == unit else 0), it) for it in DATA["entries"]),
        key=lambda x: x[0],
        reverse=True,
    )
    return [it for sc, it in ranked if sc >= 0.5][:limit]


