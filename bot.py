def parent_of(num: str):
    for n in range(len(num) - 1, 1, -1):
        if num[:n] in BY_NUM:
            return BY_NUM[num[:n]]
    return None


def children_of(num: str) -> list:
    return [a for a in SCF if a["num"] != num and a["num"].startswith(num)]


def fmt_acct(a: dict) -> str:
    return f"<code>{a['num']}</code> ← {esc(a['name'])}"


def scf_by_number(num: str) -> str:
    a = BY_NUM.get(num)
    if a:
        msg = f"🔢 <b>الحساب {a['num']}</b>\n{esc(a['name'])}\n\n"
        msg += f"📂 الصنف {a['cls']}: {CLASSES[a['cls']]}"
        p = parent_of(a["num"])
        if p:
            msg += f"\n⬆️ تابع للحساب: {fmt_acct(p)}"
        kids = children_of(a["num"])
        if kids:
            msg += "\n\n⬇️ الحسابات الفرعية:\n" + "\n".join(fmt_acct(k) for k in kids[:12])
        return msg
    p = parent_of(num)
    if p:
        return (
            f"الرقم <code>{esc(num)}</code> غير مدرج في المدونة المعتمدة، "
            f"لكنه يتبع الحساب:\n{fmt_acct(p)}\n📂 الصنف {p['cls']}: {CLASSES[p['cls']]}"
        )
    if num[:1] in "1234567" and len(num) <= 2:
        c = int(num[0])
        return f"الرقم <code>{esc(num)}</code> غير موجود، لكن الصنف {c} هو: {CLASSES[c]}"
    return ""


def scf_by_class(c: int) -> str:
    rows = [a for a in SCF if a["cls"] == c and len(a["num"]) == 2]
    return (
        f"📂 <b>الصنف {c}: {CLASSES[c]}</b>\n\n"
        + "\n".join(fmt_acct(a) for a in rows)
        + "\n\nاكتب رقم أي حساب لترى حساباته الفرعية."
    )


def scf_by_name(query: str):
    q = tokens(query)
    if not q:
        return []
    ranked = []
    for a in SCF:
        hay = tokens(a["name"])
        hits = 0
        for w in q:
            if w in hay:
                hits += 1
            elif w.isalpha() and any(
                h.isalpha() and SequenceMatcher(None, w, h).ratio() >= 0.8 for h in hay
            ):
                hits += 1
        s = hits / len(q)
        if s >= 0.5:
            ranked.append((-s, abs(len(hay) - len(q)), len(a["num"]), a))
    ranked.sort(key=lambda x: x[:3])
    return [r[3] for r in ranked[:4]]


def scf_answer(text: str) -> str:
    t = norm(text)
    m = re.search(r"صنف\s*([1-7])\b", t)
    if m:
        return scf_by_class(int(m.group(1)))
    m = re.search(r"\d+", t)
    if m:
        return scf_by_number(m.group(0))
    found = scf_by_name(text)
    if not found:
        return ""
    best = found[0]
    msg = scf_by_number(best["num"])
    if len(found) > 1:
        msg += "\n\n🔎 قد تقصد أيضاً 🤩:\n" + "\n".join(fmt_acct(a) for a in found[1:])
    return msg


