def search_defs(query: str, unit: int = None, limit: int = 3) -> list:
    ranked = sorted(
        ((score(query, it) + (0.01 if it["unit"] == unit else 0), it) for it in DATA["defs"]),
        key=lambda x: x[0],
        reverse=True,
    )
    return [it for sc, it in ranked if sc >= 0.5][:limit]


