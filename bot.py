        await update.message.reply_text(msg, parse_mode=ParseMode.HTML)
        kb = terms_keyboard(best["unit"])
        await update.message.reply_text(motiv() + "\n\nتريد تعريفاً آخر؟ اضغط أو اكتب اسمه 👇😍", reply_markup=kb)
