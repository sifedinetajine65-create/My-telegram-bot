AR_MARKS = re.compile("[\u0610-\u061a\u064b-\u065f\u0670\u0640]")
STOP_RAW = {
    "قيد", "تعريف", "حساب", "رقم", "عن", "في", "من", "على", "ما", "هو", "هي",
    "ماذا", "اعطني", "اعطيني", "اريد", "ابحث", "مصطلح",
}


def norm(text: str) -> str:
    text = text.translate(str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789"))
    text = AR_MARKS.sub("", text)
    text = re.sub("[إأآ]", "ا", text)
    text = text.replace("ى", "ي").replace("ة", "ه")
    return text.lower().strip()


STOP = {norm(w) for w in STOP_RAW}


def tokens(text: str) -> list:
    out = []
    for w in re.findall(r"\w+", norm(text)):
        if w.startswith("ال") and len(w) > 3:
            w = w[2:]
        if w not in STOP:
            out.append(w)
    return out


def score(query: str, item: dict) -> float:
    q = tokens(query)
    if not q:
        return 0.0
    hay = tokens(item["title"] + " " + item.get("keys", ""))
    hits = 0
    for w in q:
        if w in hay:
            hits += 1
        elif w.isalpha() and any(
            h.isalpha() and SequenceMatcher(None, w, h).ratio() >= 0.8 for h in hay
        ):
            hits += 1
    return hits / len(q)


def search(section: str, query: str, limit: int = 3) -> list:
    ranked = sorted(
        ((score(query, it), it) for it in DATA[section]),
        key=lambda x: x[0],
        reverse=True,
    )
    return [it for s, it in ranked if s >= 0.5][:limit]


